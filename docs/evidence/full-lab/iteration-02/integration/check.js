async page => {
  const checks=[],check=(name,pass,data)=>checks.push({name,pass:!!pass,...(data===undefined?{}:{data})});
  const time=async()=>parseFloat(await page.locator('#lab-time').innerText());
  await page.waitForFunction(()=>parseFloat(document.querySelector('#lab-time').textContent)>20,{},{timeout:35000});
  const before=await time(), initial=await page.evaluate(()=>window.__liveQA);
  const run=initial.runs.at(-1)?.id, chunks=initial.chunks.filter(c=>c.runId===run);
  check('continuous-beyond-16-seconds',before>20,{time:before});
  check('one-live-start',initial.runs.length===1,initial.runs);
  check('contiguous-actual-new-samples',chunks.length>80&&chunks.every((c,i)=>i===0||c.start===chunks[i-1].start+chunks[i-1].count));
  check('bounded-history',chunks.every(c=>c.historyCount<=4096&&c.historyEnd-c.historyStart===c.historyCount));
  check('learned-output-persists-past-old-boundary',chunks.some(c=>c.start>32000&&c.start<34000&&c.maxU>0.001));
  check('not-looped-q',chunks.find(c=>c.start===0)?.q!==chunks.find(c=>c.start===32000)?.q);
  check('real-field-after-16s',initial.fields.some(f=>f.valid&&f.time>16));
  check('no-seek-for-live',await page.locator('#lab-seek').isDisabled());
  await page.locator('#lab-play').click();await page.waitForTimeout(120);
  const paused=await time(), requests=await page.evaluate(()=>window.__liveQA.chunks.length);
  await page.waitForTimeout(800);
  check('pause-freezes-time',Math.abs(await time()-paused)<0.02,{paused,after:await time()});
  check('pause-stops-producer',await page.evaluate(()=>window.__liveQA.chunks.length)===requests);
  await page.locator('#lab-seat').selectOption('3');await page.locator('#lab-comparison').selectOption('d');
  check('live-comparison-same-time',Math.abs(await time()-paused)<0.02&&/D RR/.test(await page.locator('#lab-signal-title').innerText()));
  await page.getByRole('button',{name:'Q4 · 查看轮端激励源信号和频谱',exact:true}).click();
  check('live-q-independent-from-listening',/Q4/.test(await page.locator('#lab-signal-title').innerText())&&await page.locator('#lab-seat').inputValue()==='3'&&await page.locator('#lab-comparison').inputValue()==='d');
  await page.locator('#lab-play').click();await page.waitForTimeout(1000);
  check('resume-preserves-clock',await time()>paused+0.7);
  await page.locator('#lab-explode').click();await page.locator('#lab-section').selectOption('x');await page.waitForTimeout(1200);
  check('views-do-not-reset-live',await page.evaluate(()=>window.__liveQA.runs.at(-1)?.id)===run&&await time()>paused+1.5);
  await page.screenshot({path:'output/playwright/live-lab/live-section.png',fullPage:true});
  await page.locator('#lab-rnc').uncheck();
  check('live-dirty-clears-and-stops',await page.locator('#lab-play').isDisabled()&&await time()===0&&/等待/.test(await page.locator('#lab-signal-title').innerText()));
  await page.locator('#lab-calculate').click();
  await page.waitForFunction(()=>document.querySelector('#lab-time').textContent.includes('实时')&&parseFloat(document.querySelector('#lab-time').textContent)>2,{},{timeout:15000});
  const off=await page.evaluate(()=>{const id=window.__liveQA.runs.at(-1).id;return window.__liveQA.chunks.filter(c=>c.runId===id);});
  check('rnc-off-actual-zero',off.length>5&&off.every(c=>c.maxU===0&&c.maxA===0&&c.maxDE===0));
  const offRun=off.at(-1)?.runId;
  await page.locator('#lab-replay').click();
  await page.waitForFunction(id=>window.__liveQA.runs.at(-1)?.id!==id,offRun,{timeout:15000});
  check('restart-new-run-and-clock',await time()<1&&await page.evaluate(()=>window.__liveQA.runs.at(-1)?.id)!==offRun);
  await page.locator('#lab-cancel').click();
  check('stop-explicit',await page.locator('#lab-play').isDisabled()&&/已结束/.test(await page.locator('#lab-status').innerText()));
  await page.locator('#lab-mode').selectOption('replay');await page.locator('#lab-calculate').click();
  await page.locator('#lab-status').filter({hasText:'实验就绪'}).waitFor({timeout:30000});
  check('batch-still-works',!(await page.locator('#lab-seek').isDisabled())&&/16/.test(await page.locator('#lab-time').innerText()));
  const errors=await page.evaluate(()=>window.__liveQA.errors);check('no-page-errors',errors.length===0,errors);
  return {passed:checks.filter(c=>c.pass).length,failed:checks.filter(c=>!c.pass).length,checks,data:await page.evaluate(()=>window.__liveQA)};
}
