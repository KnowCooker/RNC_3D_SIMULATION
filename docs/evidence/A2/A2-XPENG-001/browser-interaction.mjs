import { chromium } from '../../../../test-results/a2-tools/browser/node_modules/playwright-core/index.mjs';
import { writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1050 } });
const checks = [], errors = []; page.on('pageerror', e => errors.push(String(e)));
const check = (ok, label) => { assert.ok(ok, label); checks.push(label); };
try {
  await page.goto('http://127.0.0.1:5197/#xpeng');
  await page.locator('.lab-xpeng-picker:not([hidden])').waitFor();
  await page.getByRole('button', { name: '车间三维场景', exact: true }).click();
  const viewer = page.locator('#lab-viewer'), canvas = viewer.locator('canvas'), panel = page.locator('.lab-showroom-panel'), assembly = page.locator('.lab-showroom-assembly');
  await viewer.scrollIntoViewIfNeeded(); await page.waitForTimeout(500);
  const size = await canvas.boundingBox();
  await canvas.click({ position: { x: size.width * .5, y: size.height * .52 } });
  check((await page.getByLabel('选择写实车部件', { exact: true }).inputValue()).length > 0, 'actual canvas raycast selects a semantic part');
  await panel.getByRole('button', { name: '全部复位', exact: true }).click();
  const before = await canvas.screenshot();
  await page.getByRole('button', { name: '深红车漆', exact: true }).click();
  const painted = await canvas.screenshot();
  check(!before.equals(painted), 'paint changes rendered pixels');
  await page.getByLabel('写实车剖面', { exact: true }).selectOption('x');
  await viewer.screenshot({ path: 'docs/evidence/A2/A2-XPENG-001/x9-section.png' });
  check(!(await canvas.screenshot()).equals(painted), 'section changes rendered geometry');
  await panel.getByRole('button', { name: '全部复位', exact: true }).click();
  await panel.locator('summary').click();
  await assembly.getByRole('button', { name: '自动拆解', exact: true }).click();
  await page.waitForFunction(() => /已拆 [1-9]/.test(document.querySelector('.lab-showroom-assembly p').textContent));
  await assembly.getByRole('button', { name: '暂停自动拆解', exact: true }).click();
  const detached = await assembly.locator('p').innerText(); await page.waitForTimeout(1000);
  check(await assembly.locator('p').innerText() === detached, 'automatic disassembly pauses');
  await assembly.getByRole('button', { name: '自动回装', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.lab-showroom-assembly p').textContent.startsWith('已拆 0'));
  check((await assembly.locator('p').innerText()).startsWith('已拆 0'), 'automatic reverse assembly completes');
  // Rapid switches exercise generation guards and disposal instead of only settled sequential loads.
  for (const id of ['m03', 'gx', 'p7plus', 'l03', 'x9', 'gx']) await page.getByLabel('选择小鹏车型', { exact: true }).selectOption(id);
  await page.waitForFunction(() => document.querySelector('.lab-showroom-panel > strong').textContent.startsWith('小鹏 GX'));
  check(await page.getByLabel('选择小鹏车型', { exact: true }).inputValue() === 'gx', 'rapid switching retains latest model');
  const assembled = await canvas.screenshot();
  await canvas.hover(); await page.mouse.wheel(0, -250); await page.waitForTimeout(500);
  check(!(await canvas.screenshot()).equals(assembled), 'wheel zoom changes rendered view');
  const rect = await canvas.boundingBox();
  await page.mouse.move(rect.x + rect.width * .5, rect.y + rect.height * .65); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .57, rect.y + rect.height * .69, { steps: 12 }); await page.mouse.up();
  await page.waitForTimeout(500); check(!(await canvas.screenshot()).equals(assembled), 'drag orbit changes rendered view');
  check(errors.length === 0, 'no runtime errors during direct interaction');
  await writeFile('docs/evidence/A2/A2-XPENG-001/interaction-results.json', JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  console.log(`${checks.length} direct interaction checks passed`);
} finally { await browser.close(); }
